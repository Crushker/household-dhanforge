function buildDOC(doc: DocId, hh: Household, m: Member) {
  const who = `${m.name} · ${hh.familyName} household, ${hh.city.name}`;
  let html = "";

  if (doc === "cibil" && m.cibil != null) {
    html = docHTML(`CIBIL Credit Report — ${who}`, [
      ["CIBIL Score", `${m.cibil} (${bandLabel(m.cibil)})`], ["Score Range", "300–900"], ["PAN", m.pan ?? "—"],
    ], [{
      head: ["Account", "Institution", "Type", "Amount", "Status", "Open Since"],
      rows: m.tradelines.map((t) => [t.account, t.institution, t.type, inr2(t.amount), t.status, dateShort(t.since)]),
    }], ["Factors: payment history, utilisation, credit age, credit mix and enquiries are derived from synthetic behaviour."]);
  }
  if (doc === "bank") {
    const last = m.txns[m.txns.length - 1];
    const first = m.txns[0];
    html = docHTML(`${m.bankName} — Bank Statement`, [
      ["Account Holder", m.name], ["Account Number", m.accountNo], ["IFSC", m.ifsc], ["Branch", m.branch],
      ["Period", first && last ? `${dateShort(first.date)} – ${dateShort(last.date)}` : "—"],
      ["Closing Balance", last ? inr2(last.balance) : "—"],
    ], [{
      head: ["Date", "Narration", "Reference", "Debit", "Credit", "Balance"],
      rows: m.txns.map((t) => [dateShort(t.date), t.narration, t.ref, t.amount < 0 ? inr2(-t.amount) : "", t.amount > 0 ? inr2(t.amount) : "", inr2(t.balance)]),
    }]);
  }
  if (doc === "card" && m.card) {
    const period = m.card.txns.filter((t) => t.date.startsWith(stmtMonthKey()));
    const purchases = period.reduce((s, t) => s + t.amount, 0);
    html = docHTML(`${m.card.bank} — Credit Card Statement`, [
      ["Card", `${m.card.product} · ${m.card.numberMasked}`], ["Credit Limit", inr2(m.card.limit)],
      ["Statement Cycle", stmtMonthLabel()], ["Payment Due", dueDateLabel()],
      ["Total Amount Due", inr2(purchases)], ["Minimum Amount Due", inr2(Math.round(purchases * 0.05))],
    ], [{
      head: ["Date", "Particulars", "Amount"],
      rows: period.map((t) => [dateShort(t.date), t.detail, inr2(t.amount)]),
    }], [`Reward points earned this cycle: ${Math.round(purchases / 100)}`]);
  }
  if (doc === "loan" && m.loan) {
    html = docHTML(`${m.loan.lender} — ${m.loan.type} Statement`, [
      ["Loan Account", m.loan.accountNo], ["Sanction Date", dateShort(m.loan.sanctionDate)],
      ["Principal", inr2(m.loan.principal)], ["Rate", `${m.loan.rate}% p.a.`], ["Tenure", `${m.loan.tenureMonths} months`],
      ["EMI", inr2(m.loan.emi)], ["Outstanding", inr2(m.loan.outstanding)], ["Next Due", dateShort(m.loan.nextDue)],
    ], [{
      head: ["#", "Due Date", "EMI", "Principal", "Interest", "Balance"],
      rows: m.loan.schedule.map((s) => [s.no, dateShort(s.date), inr2(s.emi), inr2(s.principal), inr2(s.interest), inr2(s.balance)]),
    }]);
  }
  if (doc === "form16" && m.form16) {
    const f = m.form16;
    html = docHTML(`Form 16 — ${f.ay}`, [
      ["Employer", f.employer], ["Employer TAN", f.tan], ["Employee", m.name], ["Employee PAN", m.pan ?? "—"],
      ["Financial Year", f.fy], ["Assessment Year", f.ay],
    ], [{
      head: ["Part B — Computation", "Amount"],
      rows: [
        ["Gross Salary", inr2(f.gross)], ["Basic", inr2(f.basic)], ["HRA", inr2(f.hra)], ["Special Allowance", inr2(f.special)],
        ["Standard Deduction u/s 16(ia)", `(${inr2(f.stdDeduction)})`], ["HRA Exempt u/s 10(13A)", `(${inr2(f.hraExempt)})`],
        ["EPF (employee share)", `(${inr2(f.epfEmployee)})`], ["Deduction u/s 80C", `(${inr2(f.c80)})`],
        ["Deduction u/s 80D", `(${inr2(f.d80)})`], ["Income from Other Sources", inr2(f.otherIncome)],
        ["Net Taxable Income", inr2(f.taxable)], ["Income Tax", inr2(f.tax)], ["Cess @4%", inr2(f.cess)],
        ["Total TDS", inr2(f.totalTax)],
      ],
    }]);
  }
  if (doc === "itr") {
    const t = computeItr(m);
    html = docHTML(`ITR-1 (Sahaj) Acknowledgement — ${t.ay}`, [
      ["Name", m.name], ["PAN", m.pan ?? "—"], ["Assessment Year", t.ay],
      ["Acknowledgement No.", t.ack], ["Filing Date", dateShort(new Date().toISOString())],
    ], [{
      head: ["Computation", "Amount"],
      rows: [
        ["Gross Total Income", inr2(t.grossTotal)], ["Deductions", `(${inr2(t.deductions)})`], ["Total Income", inr2(t.totalIncome)],
        ["Tax Liability", inr2(t.taxLiability)], ["TDS / Taxes Paid", inr2(t.tds)],
        t.refund > 0 ? ["Refund Issuable", inr2(t.refund)] : ["Tax Payable", inr2(t.payable)],
      ],
    }]);
  }

  downloadBlob(html, `DhanForge_${safeName(m)}_${doc.toUpperCase()}.doc`, "application/msword");
}


type Pdf = jsPDF;

function pdfHeader(doc: Pdf, title: string, subtitle: string, right: string) {
  doc.setFillColor(...NAVY);
  doc.rect(0, 0, 595, 78, "F");
  doc.setFillColor(...LIME);
  doc.rect(0, 78, 595, 3, "F");
  doc.setTextColor(242, 246, 255);
  doc.setFont("helvetica", "bold");
  doc.setFontSize(17);
  doc.text(title, 36, 36);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(9.5);
  doc.setTextColor(...FOG);
  doc.text(subtitle, 36, 54);
  doc.setTextColor(...LIME);
  doc.setFontSize(8);
  doc.text(right, 559, 36, { align: "right" });
  doc.setTextColor(...FOG);
  doc.text("SYNTHETIC DATA — NOT REAL", 559, 50, { align: "right" });
  return 100;
}

function pdfMeta(doc: Pdf, rows: [string, string][], yStart?: number, cols = 2): number {
  const y =
    yStart ??
    ((doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? 84) + 18;
  const colW = (595 - 72) / cols;
  doc.setFontSize(9);
  rows.forEach((r, i) => {
    const cx = 36 + (i % cols) * colW;
    const cy = y + Math.floor(i / cols) * 34;
    doc.setFont("helvetica", "normal");
    doc.setTextColor(...FOG);
    doc.text(r[0].toUpperCase(), cx, cy);
    doc.setFont("helvetica", "bold");
    doc.setTextColor(...INKP);
    doc.setFontSize(10.5);
    doc.text(r[1], cx, cy + 14);
    doc.setFontSize(9);
  });
  return y + Math.ceil(rows.length / cols) * 34 + 6;
}

function pdfTable(doc: Pdf, head: string[], body: (string | number)[][], opts?: { right?: number[]; startY?: number }) {
  const lastY = (doc as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY;
  autoTable(doc, {
    head: [head],
    body,
    startY: opts?.startY ?? (lastY ? lastY + 12 : 100),
    margin: { left: 36, right: 36 },
    styles: { font: "helvetica", fontSize: 8.2, cellPadding: 4.5, textColor: [40, 48, 66] },
    headStyles: { fillColor: NAVY, textColor: [242, 246, 255], fontStyle: "bold" },
    alternateRowStyles: { fillColor: [244, 247, 252] },
    columnStyles: Object.fromEntries((opts?.right ?? []).map((c) => [c, { halign: "right" as const }])),
  });
}

function pdfFooter(doc: Pdf) {
  const pages = doc.getNumberOfPages();
  for (let i = 1; i <= pages; i++) {
    doc.setPage(i);
    doc.setFontSize(7.5);
    doc.setTextColor(...FOG);
    doc.text(`Generated by DhanForge · Synthetic household data for testing · Page ${i} of ${pages}`, 297.5, 822, { align: "center" });
  }
}

function bandLabel(score: number): string {
  return score >= 750 ? "Excellent" : score >= 700 ? "Good" : score >= 650 ? "Fair" : "Poor";
}



function buildPDF(doc: DocId, hh: Household, m: Member) {
  const pdf = new jsPDF({ unit: "pt", format: "a4" });
  const who = `${m.name} · ${hh.familyName} household, ${hh.city.name}`;

  if (doc === "cibil" && m.cibil != null) {
    let y = pdfHeader(pdf, "CIBIL Credit Report", who, `Score ${m.cibil}`);
    pdf.setFillColor(...CARD);
    pdf.roundedRect(36, y, 523, 64, 10, 10, "F");
    pdf.setTextColor(...LIME);
    pdf.setFont("helvetica", "bold");
    pdf.setFontSize(30);
    pdf.text(`${m.cibil}`, 56, y + 44);
    pdf.setFontSize(10);
    pdf.setTextColor(242, 246, 255);
    pdf.text(`Rating: ${bandLabel(m.cibil)}  ·  Range 300–900`, 120, y + 38);
    pdf.setFont("helvetica", "normal");
    pdf.setFontSize(8.5);
    pdf.setTextColor(...FOG);
    pdf.text("Score derived from 36 months of synthetic repayment behaviour.", 120, y + 52);
    pdfTable(pdf, ["Factor", "Status", "Impact"], [
      ["Payment History", m.cibil >= 700 ? "Excellent — 0 missed EMIs" : "Good — 1 late mark", m.cibil >= 700 ? "Positive" : "Neutral"],
      ["Credit Utilisation", m.card ? `${Math.round((m.card.lastStatementTotal / m.card.limit) * 100)}% of limit` : "No revolving credit", m.card && m.card.lastStatementTotal / m.card.limit < 0.35 ? "Positive" : "Negative"],
      ["Credit Age", `${Math.max(1, Math.min(14, m.age - 21))}+ years`, "Positive"],
      ["Credit Mix", m.loan && m.card ? "Secured + revolving" : "Single type", m.loan && m.card ? "Positive" : "Neutral"],
      ["Recent Enquiries", `${m.age % 3} in last 6 months`, m.age % 3 === 0 ? "Positive" : "Neutral"],
    ], { startY: y + 84 });
    pdfTable(pdf, ["Account", "Institution", "Type", "Amount", "Status", "Open Since"],
      m.tradelines.map((t) => [t.account, t.institution, t.type, inr2(t.amount), t.status, dateShort(t.since)]),
      { right: [3] });
    pdfFooter(pdf);
  }

  if (doc === "bank") {
    const first = m.txns[0];
    const last = m.txns[m.txns.length - 1];
    const opening = first ? first.balance - first.amount : m.openingBalance;
    let y = pdfHeader(pdf, `${m.bankName} — Bank Statement`, who, `A/c ••••${m.accountNo.slice(-4)}`);
    y = pdfMeta(pdf, [
      ["Account Holder", m.name], ["Account Number", m.accountNo],
      ["IFSC", m.ifsc], ["Branch", m.branch],
      ["Statement Period", first && last ? `${dateShort(first.date)} – ${dateShort(last.date)}` : "—"],
      ["Opening Balance", inr2(opening)],
    ]);
    const rows = m.txns.map((t) => [
      dateShort(t.date), t.narration, t.ref,
      t.amount < 0 ? plain(-t.amount) : "", t.amount > 0 ? plain(t.amount) : "", plain(t.balance),
    ]);
    pdfTable(pdf, ["Date", "Narration", "Reference", "Debit (₹)", "Credit (₹)", "Balance (₹)"], rows, { right: [3, 4, 5], startY: y });
    const cr = m.txns.filter((t) => t.amount > 0).reduce((s, t) => s + t.amount, 0);
    const dr = m.txns.filter((t) => t.amount < 0).reduce((s, t) => s - t.amount, 0);
    pdf.setFontSize(9);
    pdf.setTextColor(...INKP);
    pdf.setFont("helvetica", "bold");
    const fy = (pdf as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y;
    pdf.text(`Total Credits: ${inr2(cr)}    Total Debits: ${inr2(dr)}    Closing Balance: ${inr2(last?.balance ?? opening)}`, 36, fy + 18);
    pdfFooter(pdf);
  }

  if (doc === "card" && m.card) {
    const key = stmtMonthKey();
    const period = m.card.txns.filter((t) => t.date.startsWith(key));
    const purchases = period.reduce((s, t) => s + t.amount, 0);
    let y = pdfHeader(pdf, `${m.card.bank} — Credit Card Statement`, who, m.card.product);
    y = pdfMeta(pdf, [
      ["Card Number", m.card.numberMasked], ["Credit Limit", inr2(m.card.limit)],
      ["Statement Cycle", stmtMonthLabel()], ["Payment Due Date", dueDateLabel()],
      ["Total Amount Due", inr2(purchases)], ["Minimum Amount Due", inr2(Math.round(purchases * 0.05))],
    ]);
    pdfTable(pdf, ["Date", "Particulars", "Amount (₹)"],
      period.map((t) => [dateShort(t.date), t.detail, plain(t.amount)]), { right: [2], startY: y });
    pdf.setFontSize(9);
    pdf.setFont("helvetica", "bold");
    pdf.setTextColor(...INKP);
    const fy = (pdf as unknown as { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? y;
    pdf.text(`Opening Balance: ₹0.00 (paid in full) · Finance Charge: ₹0.00 · Reward Points Earned: ${Math.round(purchases / 100)}`, 36, fy + 18);
    pdfFooter(pdf);
  }

  if (doc === "loan" && m.loan) {
    let y = pdfHeader(pdf, `${m.loan.lender} — Loan Statement`, who, m.loan.type);
    y = pdfMeta(pdf, [
      ["Loan Account", m.loan.accountNo], ["Sanction Date", dateShort(m.loan.sanctionDate)],
      ["Principal Amount", inr2(m.loan.principal)], ["Interest Rate", `${m.loan.rate}% p.a.`],
      ["Tenure", `${m.loan.tenureMonths} months`], ["Monthly EMI", inr2(m.loan.emi)],
      ["Installments Paid", `${m.loan.paidInstallments} of ${m.loan.tenureMonths}`],
      ["Outstanding Principal", inr2(m.loan.outstanding)],
    ]);
    pdfTable(pdf, ["#", "Due Date", "EMI (₹)", "Principal (₹)", "Interest (₹)", "Balance (₹)"],
      m.loan.schedule.map((s) => [s.no, dateShort(s.date), plain(s.emi), plain(s.principal), plain(s.interest), plain(s.balance)]),
      { right: [2, 3, 4, 5], startY: y });
    pdfFooter(pdf);
  }

  if (doc === "form16" && m.form16) {
    const f = m.form16;
    let y = pdfHeader(pdf, "Form 16 — TDS Certificate", `${who} · ${f.fy} · ${f.ay}`, `PAN ${m.pan}`);
    y = pdfMeta(pdf, [
      ["Employer", f.employer], ["Employer TAN", f.tan],
      ["Employee", m.name], ["Employee PAN", m.pan ?? "—"],
      ["Assessment Year", f.ay], ["Gross Salary", inr2(f.gross)],
    ]);
    pdfTable(pdf, ["Part B — Income & Deductions", "Amount (₹)"], [
      ["Gross Salary (u/s 17(1))", plain(f.gross)],
      ["  — Basic", plain(f.basic)], ["  — House Rent Allowance", plain(f.hra)], ["  — Special Allowance", plain(f.special)],
      ["Less: Standard Deduction (u/s 16(ia))", `(${plain(f.stdDeduction)})`],
      ["Less: HRA Exempt (u/s 10(13A))", `(${plain(f.hraExempt)})`],
      ["Less: Employee EPF Contribution", `(${plain(f.epfEmployee)})`],
      ["Less: Deduction u/s 80C", `(${plain(f.c80)})`],
      ["Less: Deduction u/s 80D", `(${plain(f.d80)})`],
      ["Income from Other Sources", plain(f.otherIncome)],
      ["Net Taxable Income", plain(f.taxable)],
      ["Income Tax", plain(f.tax)], ["Health & Education Cess (4%)", plain(f.cess)],
      ["Total Tax Deducted at Source", plain(f.totalTax)],
      ["Average Monthly TDS", plain(f.tdsMonthly)],
    ], { right: [1], startY: y });
    pdfFooter(pdf);
  }

  if (doc === "itr") {
    const t = computeItr(m);
    let y = pdfHeader(pdf, "ITR-1 (Sahaj) — Acknowledgement", `${who} · ${t.ay}`, `ACK ${t.ack}`);
    y = pdfMeta(pdf, [
      ["PAN", m.pan ?? "—"], ["Assessment Year", t.ay],
      ["Return Form", "ITR-1 (Sahaj)"], ["Filing Mode", "e-Filed with Aadhaar OTP"],
      ["Filing Date", dateShort(new Date().toISOString())], ["Acknowledgement No.", t.ack],
    ]);
    pdfTable(pdf, ["Computation", "Amount (₹)"], [
      ["Gross Total Income", plain(t.grossTotal)],
      ["Total Deductions (Ch. VI-A & others)", `(${plain(t.deductions)})`],
      ["Total Income", plain(t.totalIncome)],
      ["Tax Liability (incl. cess)", plain(t.taxLiability)],
      ["TDS / Taxes Paid", plain(t.tds)],
      t.refund > 0 ? ["Refund Issuable", plain(t.refund)] : ["Tax Payable (Self-Assessment)", plain(t.payable)],
    ], { right: [1], startY: y });
    pdfFooter(pdf);
  }

  pdf.save(`DhanForge_${safeName(m)}_${doc.toUpperCase()}.pdf`);
}

function stmtMonthKey(): string {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth() - 1, 1);
  return `${d.getFullYear()}-${`${d.getMonth() + 1}`.padStart(2, "0")}`;
}
function stmtMonthLabel(): string {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth() - 1, 1);
  return d.toLocaleDateString("en-IN", { month: "long", year: "numeric" });
}
function dueDateLabel(): string {
  const now = new Date();
  return new Date(now.getFullYear(), now.getMonth(), 18).toLocaleDateString("en-IN", { day: "2-digit", month: "short", year: "numeric" });
}


function sheetFromAOA(name: string, aoa: (string | number)[][]) {
  const ws = XLSX.utils.aoa_to_sheet(aoa);
  ws["!cols"] = aoa[0]?.map((_, c) => ({
    wch: Math.max(12, ...aoa.map((r) => `${r[c] ?? ""}`.length + 2)),
  }));
  return { name: name.slice(0, 31), ws };
}

function memberSheets(hh: Household, m: Member) {
  const sheets: { name: string; ws: XLSX.WorkSheet }[] = [];
  const fn = `${safeName(m).slice(0, 9)}${m.id.replace("m", "")}`;

  sheets.push(sheetFromAOA(`${fn}-Bank`, [
    [`${m.bankName} — Bank Statement`], [m.name], [`A/c ${m.accountNo}`, `IFSC ${m.ifsc}`, m.branch],
    ["Date", "Narration", "Reference", "Debit", "Credit", "Balance"],
    ...m.txns.map((t) => [dateShort(t.date), t.narration, t.ref, t.amount < 0 ? -t.amount : 0, t.amount > 0 ? t.amount : 0, t.balance]),
  ]));

  if (m.card) {
    const period = m.card.txns.filter((t) => t.date.startsWith(stmtMonthKey()));
    sheets.push(sheetFromAOA(`${fn}-Card`, [
      [`${m.card.product} — Credit Card Statement`], [m.card.numberMasked], [`Limit ${m.card.limit}`, stmtMonthLabel()],
      ["Date", "Particulars", "Category", "Amount"],
      ...period.map((t) => [dateShort(t.date), t.detail, CATEGORY_META[t.category as TxnCategory].label, t.amount]),
      [], ["Total Purchases", period.reduce((s, t) => s + t.amount, 0)], ["Minimum Due", Math.round(period.reduce((s, t) => s + t.amount, 0) * 0.05)],
    ]));
  }

  if (m.loan) {
    sheets.push(sheetFromAOA(`${fn}-Loan`, [
      [`${m.loan.type} — ${m.loan.lender}`], [`A/c ${m.loan.accountNo}`, `${m.loan.rate}% p.a.`, `${m.loan.tenureMonths} months`],
      ["#", "Due Date", "EMI", "Principal", "Interest", "Balance"],
      ...m.loan.schedule.map((s) => [s.no, dateShort(s.date), s.emi, s.principal, s.interest, s.balance]),
    ]));
  }

  if (m.form16) {
    const f = m.form16;
    sheets.push(sheetFromAOA(`${fn}-Form16`, [
      [`Form 16 — ${f.ay}`], [f.employer, `TAN ${f.tan}`], [m.name, `PAN ${m.pan}`],
      ["Head", "Amount"],
      ["Gross Salary", f.gross], ["Basic", f.basic], ["HRA", f.hra], ["Special", f.special],
      ["Standard Deduction", -f.stdDeduction], ["HRA Exempt", -f.hraExempt], ["EPF (employee)", -f.epfEmployee],
      ["80C", -f.c80], ["80D", -f.d80], ["Other Income", f.otherIncome], ["Taxable Income", f.taxable],
      ["Income Tax", f.tax], ["Cess", f.cess], ["Total TDS", f.totalTax],
    ]));
  }

  if (m.age >= 18 && m.employment.monthlyGross > 0) {
    const t = computeItr(m);
    sheets.push(sheetFromAOA(`${fn}-ITR`, [
      [`ITR-1 Acknowledgement — ${t.ay}`], [m.name, `PAN ${m.pan}`, `ACK ${t.ack}`],
      ["Head", "Amount"],
      ["Gross Total Income", t.grossTotal], ["Deductions", -t.deductions], ["Total Income", t.totalIncome],
      ["Tax Liability", t.taxLiability], ["TDS", t.tds], ["Refund", t.refund], ["Payable", t.payable],
    ]));
  }

  if (m.age >= 18) {
    sheets.push(sheetFromAOA(`${fn}-CIBIL`, [
      [`CIBIL Report — ${m.name}`], ["Score", m.cibil ?? "NH (No History)"],
      ["Account", "Institution", "Type", "Amount", "Status", "Since"],
      ...m.tradelines.map((t) => [t.account, t.institution, t.type, t.amount, t.status, dateShort(t.since)]),
    ]));
  }
  return sheets;
}

function buildMemberXLSX(hh: Household, m: Member) {
  const wb = XLSX.utils.book_new();
  memberSheets(hh, m).forEach((s) => XLSX.utils.book_append_sheet(wb, s.ws, s.name));
  XLSX.writeFile(wb, `DhanForge_${safeName(m)}_AllDocs.xlsx`);
}

function buildHouseholdXLSX(hh: Household) {
  const wb = XLSX.utils.book_new();
  const roster = sheetFromAOA("Household", [
    [`DhanForge — ${hh.familyName} Household (${hh.city.name})`],
    [`Monthly Income ${hh.monthlyIncome} · Monthly Expense ${hh.monthlyExpense} · EMIs ${hh.monthlyEmi} · Net ${hh.net}`],
    ["Name", "Age", "Gender", "Role", "Occupation", "Employer", "Monthly Income", "CIBIL", "Bank", "PAN"],
    ...hh.members.map((m) => [
      m.name, m.age, m.gender, m.role, m.employment.title, m.employment.employer ?? "—",
      m.employment.monthlyTakeHome, m.cibil ?? "NH", m.bankName, m.pan ?? "—",
    ]),
  ]);
  XLSX.utils.book_append_sheet(wb, roster.ws, roster.name);
  hh.members.forEach((m) => memberSheets(hh, m).forEach((s) => XLSX.utils.book_append_sheet(wb, s.ws, s.name)));
  XLSX.writeFile(wb, `DhanForge_${hh.familyName}_Household.xlsx`);
}


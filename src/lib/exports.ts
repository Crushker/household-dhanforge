const NAVY: [number, number, number] = [14, 22, 38];
const CARD: [number, number, number] = [23, 35, 60];
const LIME: [number, number, number] = [195, 242, 77];
const FOG: [number, number, number] = [120, 136, 166];
const INKP: [number, number, number] = [28, 36, 56];

const safeName = (m: Member) => m.name.replace(/\s+/g, "");

function docAvailable(doc: DocId, m: Member): boolean {
  switch (doc) {
    case "cibil": return m.age >= 18;
    case "bank": return true;
    case "card": return !!m.card;
    case "loan": return !!m.loan;
    case "form16": return m.employment.kind === "salaried";
    case "itr": return m.age >= 18 && m.employment.monthlyGross > 0;
  }
}
export { docAvailable };


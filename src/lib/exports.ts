export function exportDoc(kind: "pdf" | "xlsx" | "doc", doc: DocId, hh: Household, m: Member) {
  if (!docAvailable(doc, m)) {
    throw new Error(`${doc} is not available for ${m.name}`);
  }
  if (kind === "pdf") buildPDF(doc, hh, m);
  else if (kind === "xlsx") buildMemberXLSX(hh, m);
  else buildDOC(doc, hh, m);
}

export function exportAllXLSX(hh: Household) {
  buildHouseholdXLSX(hh);
}
